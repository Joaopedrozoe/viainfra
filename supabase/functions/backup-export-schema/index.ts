const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), { status, headers: { ...corsHeaders, "Content-Type": "application/json" } });

const PROJECT_NAME = (Deno.env.get("BACKUP_PROJECT_ID") ?? "").trim();
const qi = (s: string) => `"${s.replace(/"/g, '""')}"`;
const ql = (s: string) => `'${s.replace(/'/g, "''")}'`;

async function sha256Hex(data: Uint8Array) {
  const h = await crypto.subtle.digest("SHA-256", data as BufferSource);
  return Array.from(new Uint8Array(h)).map((b) => b.toString(16).padStart(2, "0")).join("");
}

// deno-lint-ignore no-explicit-any
type Cat = any;

function buildDDL(cat: Cat): string {
  const out: string[] = [];
  const sec = (t: string) => out.push(`\n-- ==================== ${t} ====================`);
  out.push(`-- Esquema exportado em ${cat.generated_at} (PostgreSQL ${cat.server_version})`);
  out.push(`-- Contém apenas estrutura. Nenhum dado de tabela incluído.`);
  out.push(`-- Requer ambiente Supabase (schemas auth/storage, roles anon/authenticated/service_role).`);
  out.push(`SET check_function_bodies = false;`);

  sec("EXTENSIONS");
  for (const e of cat.extensions) {
    if (e.name === "plpgsql") continue;
    out.push(`CREATE EXTENSION IF NOT EXISTS ${qi(e.name)} WITH SCHEMA ${qi(e.schema)}; -- v${e.version}`);
  }

  sec("ENUMS");
  for (const t of cat.enums) {
    out.push(`CREATE TYPE public.${qi(t.name)} AS ENUM (${t.values.map(ql).join(", ")});`);
  }

  sec("SEQUENCES");
  for (const s of cat.sequences) out.push(s.definition);

  sec("TABLES");
  for (const t of cat.tables) {
    const cols = t.columns.map((c: Cat) => {
      let l = `  ${qi(c.name)} ${c.type}`;
      if (c.identity) l += c.identity === "a" ? " GENERATED ALWAYS AS IDENTITY" : " GENERATED BY DEFAULT AS IDENTITY";
      else if (c.generated === "s" && c.default) l += ` GENERATED ALWAYS AS (${c.default}) STORED`;
      else if (c.default) l += ` DEFAULT ${c.default}`;
      if (c.not_null) l += " NOT NULL";
      return l;
    });
    out.push(`CREATE TABLE public.${qi(t.name)} (\n${cols.join(",\n")}\n);`);
    if (t.comment) out.push(`COMMENT ON TABLE public.${qi(t.name)} IS ${ql(t.comment)};`);
  }

  sec("FUNCTIONS");
  for (const f of cat.functions) out.push(`${f.definition.trim()};`);

  sec("CONSTRAINTS (PK / UNIQUE / CHECK / EXCLUDE)");
  for (const t of cat.tables) for (const c of t.constraints) {
    if (c.type === "f" || c.type === "n") continue;
    out.push(`ALTER TABLE public.${qi(t.name)} ADD CONSTRAINT ${qi(c.name)} ${c.definition};`);
  }
  sec("FOREIGN KEYS");
  for (const t of cat.tables) for (const c of t.constraints) {
    if (c.type !== "f") continue;
    out.push(`ALTER TABLE public.${qi(t.name)} ADD CONSTRAINT ${qi(c.name)} ${c.definition};`);
  }

  sec("INDEXES");
  for (const t of cat.tables) for (const i of t.indexes) if (!i.is_constraint) out.push(`${i.definition};`);

  sec("VIEWS");
  for (const v of cat.views) {
    out.push(`CREATE ${v.kind === "m" ? "MATERIALIZED VIEW" : "VIEW"} public.${qi(v.name)} AS ${v.definition}`);
  }

  sec("TRIGGERS");
  for (const tr of cat.triggers) {
    out.push(`${tr.definition};`);
    if (tr.enabled === "D") out.push(`ALTER TABLE ${tr.table} DISABLE TRIGGER ${qi(tr.name)};`);
  }

  sec("ROW LEVEL SECURITY");
  for (const t of cat.tables) {
    if (t.rls_enabled) out.push(`ALTER TABLE public.${qi(t.name)} ENABLE ROW LEVEL SECURITY;`);
    if (t.rls_forced) out.push(`ALTER TABLE public.${qi(t.name)} FORCE ROW LEVEL SECURITY;`);
  }
  for (const p of cat.policies) {
    const roles = (Array.isArray(p.roles) ? p.roles : String(p.roles).replace(/[{}]/g, "").split(","))
      .map((r: string) => (r === "public" ? "public" : qi(r))).join(", ");
    let s = `CREATE POLICY ${qi(p.name)} ON ${p.schema}.${qi(p.table)} AS ${p.permissive} FOR ${p.command} TO ${roles}`;
    if (p.using) s += ` USING (${p.using})`;
    if (p.with_check) s += ` WITH CHECK (${p.with_check})`;
    out.push(`${s};`);
  }

  sec("GRANTS (tabelas)");
  const tg: Record<string, Record<string, string[]>> = {};
  for (const g of cat.table_grants) ((tg[g.table] ??= {})[g.grantee] ??= []).push(g.privilege);
  for (const [tbl, byRole] of Object.entries(tg)) {
    for (const r of ["anon", "authenticated", "service_role"]) out.push(`REVOKE ALL ON public.${qi(tbl)} FROM ${r};`);
    for (const [role, privs] of Object.entries(byRole)) out.push(`GRANT ${privs.join(", ")} ON public.${qi(tbl)} TO ${role};`);
  }
  sec("GRANTS (funções)");
  const fg: Record<string, Set<string>> = {};
  for (const g of cat.function_grants) (fg[g.function] ??= new Set()).add(g.grantee);
  for (const f of cat.functions) {
    const sig = `public.${qi(f.name)}(${f.identity_args})`;
    const who = fg[f.name] ?? new Set();
    if (!who.has("PUBLIC")) out.push(`REVOKE ALL ON FUNCTION ${sig} FROM PUBLIC;`);
    for (const r of ["anon", "authenticated", "service_role"]) {
      out.push(who.has(r) ? `GRANT EXECUTE ON FUNCTION ${sig} TO ${r};` : `REVOKE ALL ON FUNCTION ${sig} FROM ${r};`);
    }
  }

  sec("REALTIME");
  for (const r of cat.realtime_publication_tables) {
    out.push(`ALTER PUBLICATION supabase_realtime ADD TABLE ${r.schema}.${qi(r.table)};`);
  }

  sec("STORAGE BUCKETS (somente definição; arquivos não incluídos)");
  for (const b of cat.storage_buckets) {
    out.push(
      `INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (${ql(b.id)}, ${ql(b.id)}, ${b.public}, ${b.file_size_limit ?? "NULL"}, ${
        b.allowed_mime_types ? `ARRAY[${b.allowed_mime_types.map(ql).join(",")}]` : "NULL"
      }) ON CONFLICT (id) DO NOTHING;`,
    );
  }
  return out.join("\n") + "\n";
}

function summarize(cat: Cat) {
  return {
    extensions: cat.extensions.length,
    enums: cat.enums.length,
    sequences: cat.sequences.length,
    tables: cat.tables.length,
    columns: cat.tables.reduce((n: number, t: Cat) => n + t.columns.length, 0),
    constraints: cat.tables.reduce((n: number, t: Cat) => n + t.constraints.length, 0),
    indexes: cat.tables.reduce((n: number, t: Cat) => n + t.indexes.length, 0),
    views: cat.views.length,
    functions: cat.functions.length,
    triggers: cat.triggers.length,
    policies: cat.policies.length,
    table_grants: cat.table_grants.length,
    function_grants: cat.function_grants.length,
    storage_buckets: cat.storage_buckets.length,
    realtime_tables: cat.realtime_publication_tables.length,
  };
}

const LIMITATIONS = [
  "Schemas gerenciados (auth, storage, realtime, vault) não são exportados como DDL; só triggers em auth.users, políticas de storage.objects, definição dos buckets e tabelas da publicação realtime.",
  "Configuração do Auth (provedores, e-mail, HIBP, URLs) e Secrets não são acessíveis pelo banco — recriar manualmente.",
  "Roles do banco (anon, authenticated, service_role) e default privileges não são recriados; dependem de um ambiente Supabase.",
  "Grants de colunas, ownership de objetos e configurações por role não são exportados.",
  "Cron jobs (pg_cron) não inspecionados — extensão não instalada no momento.",
];

declare const EdgeRuntime: { waitUntil(p: Promise<unknown>): void } | undefined;

// deno-lint-ignore no-explicit-any
async function schemaArtifacts(admin: any) {
  const { data: cat, error } = await admin.rpc("backup_schema_catalog");
  if (error || !cat) throw new Error("Falha ao ler o catálogo do banco");
  const enc = new TextEncoder();
  const catalogBytes = enc.encode(JSON.stringify(cat, null, 2));
  const ddlBytes = enc.encode(buildDDL(cat));
  const gzBytes = new Uint8Array(await new Response(new Blob([ddlBytes]).stream().pipeThrough(new CompressionStream("gzip"))).arrayBuffer());
  return { cat, ddlBytes, catalogBytes, gzBytes };
}

serve((req) => handle(req).catch((e) => {
  const msg = e instanceof Error ? e.message : String(e);
  console.error("backup-export-schema: erro", msg.slice(0, 300));
  return json({ success: false, error: msg.replace(/Bearer\s+\S+/g, "Bearer [redacted]").slice(0, 300) }, 500);
}));

async function handle(req: Request): Promise<Response> {
  if (req.method === "OPTIONS") return new Response("ok", { headers: corsHeaders });
  if (req.method !== "POST") return json({ success: false, error: "Method not allowed" }, 405);

  const url = Deno.env.get("SUPABASE_URL") ?? "";
  const admin = createClient(url, Deno.env.get("SUPABASE_SERVICE_ROLE_KEY") ?? "");
  // deno-lint-ignore no-explicit-any
  let body: any = {};
  try { body = await req.json(); } catch { /* corpo vazio */ }
  const mode = typeof body?.mode === "string" ? body.mode : "dry_run";

  const receiverCfg = () => {
    const baseUrl = Deno.env.get("BACKUP_RECEIVER_URL"), token = Deno.env.get("BACKUP_RECEIVER_TOKEN");
    return baseUrl && token && /^[a-z0-9_-]{1,64}$/.test(PROJECT_NAME) ? { baseUrl, token, project: PROJECT_NAME } : null;
  };
  const buildSchema = async () => {
    const s = await schemaArtifacts(admin);
    return { items: [{ key: "db/schema/catalog.json", bytes: s.catalogBytes }, { key: "db/schema/schema.sql.gz", bytes: s.gzBytes }] };
  };
  const kick = async (runId: string) => {
    const key = await internalKey(admin);
    if (!key) return;
    try {
      await fetch(`${url}/functions/v1/backup-export-schema`, {
        method: "POST",
        headers: { "Content-Type": "application/json", apikey: Deno.env.get("SUPABASE_ANON_KEY") ?? "", "x-backup-internal": key },
        body: JSON.stringify({ mode: "step", run_id: runId }),
        signal: AbortSignal.timeout(15000),
      });
    } catch (_) { console.log("backup: próxima etapa não confirmou a tempo"); }
  };
  const background = (runId: string) => {
    const cfg = receiverCfg();
    if (!cfg) return;
    const work = (async () => {
      const r = await runSteps(admin, cfg, runId, buildSchema);
      console.log(`backup: run=${runId} step=${r}`);
      if (r === "continue") await kick(runId);
    })().catch((e) => console.error("backup: erro na etapa", e instanceof Error ? e.name : "erro"));
    if (typeof EdgeRuntime !== "undefined") EdgeRuntime.waitUntil(work);
  };

  // ---------- chamadas internas (agendador e encadeamento) ----------
  const internalHeader = req.headers.get("x-backup-internal");
  if (internalHeader) {
    const key = await internalKey(admin);
    if (!key || internalHeader.length !== key.length || internalHeader !== key) return json({ success: false, error: "Unauthorized" }, 401);
    if (mode === "step") {
      const runId = typeof body.run_id === "string" ? body.run_id : "";
      background(runId);
      return json({ success: true, accepted: true });
    }
    if (mode === "scheduled_run") {
      const cfg = receiverCfg();
      if (!cfg) return json({ success: false, error: "Backup secrets not available" }, 500);
      await recoverFinalizing(admin, cfg);
      const r = await handleScheduled(admin, body);
      console.log(`backup: scheduled outcome=${r.outcome} occurrence=${r.occurrence}`);
      if (r.outcome === "started" && r.run_id) background(r.run_id);
      if (r.outcome === "skipped_concurrency" && r.active_run) {
        const { data: a } = await admin.from("backup_runs").select("status, updated_at").eq("id", r.active_run).single();
        if (a?.status === "running" && Date.now() - new Date(a.updated_at).getTime() > 10 * 60_000) background(r.active_run);
      }
      return json({ success: true, ...r });
    }
    if (mode === "reconcile") {
      const cfg = receiverCfg();
      if (!cfg) return json({ success: false, error: "Backup secrets not available" }, 500);
      const runId = typeof body.run_id === "string" ? body.run_id : "";
      if (!/^[0-9a-f-]{36}$/.test(runId) || body.retry_job !== `backup-retry-validation${runId.replace(/-/g, "")}`) {
        return json({ success: false, error: "Invalid validation job" }, 400);
      }
      await admin.rpc("backup_unschedule_job", { _job: body.retry_job });
      const outcome = await recoverFinalizing(admin, cfg);
      return json({ success: true, outcome });
    }
    return json({ success: false, error: "Invalid mode" }, 400);
  }

  // ---------- chamadas de administrador ----------
  const authHeader = req.headers.get("Authorization");
  if (!authHeader?.startsWith("Bearer ")) return json({ success: false, error: "Unauthorized" }, 401);
  const userClient = createClient(url, Deno.env.get("SUPABASE_ANON_KEY") ?? "", { global: { headers: { Authorization: authHeader } } });
  const { data: cl, error: ce } = await userClient.auth.getClaims(authHeader.replace("Bearer ", ""));
  const userId = cl?.claims?.sub;
  if (ce || !userId) return json({ success: false, error: "Unauthorized" }, 401);
  const { data: isAdmin, error: re } = await admin.rpc("is_admin", { _user_id: userId });
  if (re || isAdmin !== true) return json({ success: false, error: "Forbidden" }, 403);
  // deno-lint-ignore no-explicit-any
  const store = makeStore(admin as any, userId);

  if (mode === "start") {
    const cfg = receiverCfg();
    if (!cfg) return json({ success: false, error: "Backup secrets not available" }, 500);
    await recoverFinalizing(admin, cfg);
    const r = await startFullRun(admin, { trigger: "manual", userId });
    if (r.conflict) return json({ success: false, error: "Já existe um backup em andamento" }, 409);
    background(r.run_id);
    return json({ success: true, run_id: r.run_id });
  }

  if (mode === "status") {
    await markMissed(admin);
    const cfg = receiverCfg();
    if (cfg) await recoverFinalizing(admin, cfg);
    const { data: active } = await admin.from("backup_runs").select("id, status, updated_at, step_lock_until")
      .in("status", ["running"]).maybeSingle();
    let resumed = false;
    if (active && Date.now() - new Date(active.updated_at).getTime() > 3 * 60_000 &&
      (!active.step_lock_until || new Date(active.step_lock_until).getTime() < Date.now())) {
      background(active.id); resumed = true;
    }
    const { data: jobs } = await admin.rpc("backup_cron_jobs");
    const { data: history } = await admin.rpc("backup_cron_history", { _limit: 10 });
    return json({ success: true, resumed, cron_jobs: jobs ?? [], cron_history: history ?? [] });
  }

  if (mode === "reconcile") {
    const cfg = receiverCfg();
    if (!cfg) return json({ success: false, error: "Backup secrets not available" }, 500);
    const runId = typeof body?.run_id === "string" ? body.run_id.toLowerCase() : "";
    const outcome = await reconcileRun(store, cfg, runId);
    console.log(`backup-export-schema: reconcile outcome=${outcome}`);
    return json({ success: outcome === "promoted" || outcome === "already_complete", mode, run_id: runId, outcome },
      outcome === "invalid_run_id" ? 400 : outcome === "not_found" ? 404 : 200);
  }

  let s;
  try { s = await schemaArtifacts(admin); } catch (_) {
    return json({ success: false, error: "Falha ao ler o catálogo do banco" }, 500);
  }
  const summary = summarize(s.cat);

  if (mode === "dry_run") {
    const arts = [
      { item_key: "db/schema/catalog.json", bytes: s.catalogBytes },
      { item_key: "db/schema/schema.sql", bytes: s.ddlBytes },
    ];
    return json({
      success: true, mode, summary, limitations: LIMITATIONS,
      artifacts: await Promise.all(arts.map(async (a) => ({ item_key: a.item_key, size_bytes: a.bytes.length, sha256: await sha256Hex(a.bytes), content: new TextDecoder().decode(a.bytes) }))),
    });
  }

  if (mode !== "upload") return json({ success: false, error: "Invalid mode" }, 400);
  const cfg = receiverCfg();
  if (!cfg) return json({ success: false, error: "Backup secrets not available" }, 500);
  const artifactsToSend = [
    { component: "db_schema", item_key: "db/schema/catalog.json", bytes: s.catalogBytes, sha256: await sha256Hex(s.catalogBytes) },
    { component: "db_schema", item_key: "db/schema/schema.sql.gz", bytes: s.gzBytes, sha256: await sha256Hex(s.gzBytes) },
  ];
  const result = await executeBackupRun(store, cfg, artifactsToSend, s.cat.generated_at);
  console.log(`backup-export-schema: run=${result.run_id} status=${result.status}`);
  return json({ success: result.status === "complete", mode, summary, limitations: LIMITATIONS, ...result });
}
